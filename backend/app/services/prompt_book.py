"""The exact wording put to the model, written out for the archive.

The methodology page says what the model was asked. That is not the same as
showing it, and for a method that leans on a language model the wording *is*
the instrument: a reader who wants to judge the results -- or repeat them on a
different corpus -- needs the literal text, the model, the decoding settings
and the vocabularies the answers were forced into.

Nothing here restates a prompt. Each one is produced by calling the same
builder the pipeline calls, with the page content replaced by a marker, so the
exported text cannot drift away from the code that ran. If a prompt changes and
this file is not updated, the export changes with it.

What the reader still cannot have is the model. ``gemma4:31b`` is served over a
metered endpoint, and it may be withdrawn or retuned without notice; identical
prompts may then give different answers. That is a real limit of this kind of
work and it is stated on the methodology page rather than hidden here.
"""
from typing import Any, Dict, List

from ..models import LinkTarget, Project
from . import links as links_svc
from . import reading as reading_svc
from .llm import llm_service

# Stands in for the page text. Long enough to be unmistakable when reading the
# file, and it keeps the truncation limits visible without pasting a whole page.
MARKER = "<<< the cleaned text of the page goes here, truncated to {n} characters >>>"

SEPARATOR = "=" * 78


def _section(title: str, note: str, body: str) -> str:
    return f"{SEPARATOR}\n{title}\n{SEPARATOR}\n\n{note.strip()}\n\n{'-' * 78}\n{body}\n"


def _vocabulary(name: str, values) -> str:
    return f"  {name}: " + ", ".join(sorted(values))


def build_prompt_book(project: Project, models: List[str]) -> str:
    """Render every prompt the pipeline uses, as it currently stands in the code."""
    parts: List[str] = []

    parts.append(f"""{SEPARATOR}
THE PROMPTS USED TO BUILD THIS ARCHIVE
{SEPARATOR}

Site studied     {project.domain}
Models           {', '.join(models) if models else 'unrecorded'}
Served by        ollama.com (metered hosted endpoint)

Each prompt below is generated by the program that produced this archive, by
calling the same function the pipeline calls and substituting a marker for the
page text. They are therefore the prompts that ran, not a description of them.

Read these alongside methodology.html, which says which step each one belongs
to and which steps used no model at all. Two steps in this archive involve no
model whatsoever -- following the links, and recovering reader comments -- and
so appear nowhere in this file.

A caution about reproducibility. Naming the model is not the same as pinning
it: it is served over a hosted endpoint and can be retuned or withdrawn, and
these prompts ask for free text as well as fixed categories. Re-running them
should reproduce the shape of these results and will not reproduce them
exactly. The categories can be checked mechanically; the summaries cannot.
""")

    # --- Step 2: the corpus-wide triage pass -----------------------------------
    parts.append(_section(
        "1. SORTING THE CORPUS  (methodology step 2)",
        """Run once for every captured page of the site. It produces the summary,
topics, tags, content type, estimated publication date and tone that the pages
listing and the theme tables are built from. This is a triage pass: it is what
lets a person find their way around several thousand captures. It is not the
close reading, which is a separate pass over a narrower set.

Where a URL was captured many times, one capture was sent and the answer copied
to the rest.""",
        llm_service.build_analysis_prompt(
            content=MARKER.format(n=8000),
            filename="<capture filename>",
            original_url="<the page's original address>",
            max_chars=10 ** 9)))

    # --- Step 4: linked material, shown how the site cited it -------------------
    target = LinkTarget(
        url="<the linked address>",
        wayback_timestamp="20120704120000",
        first_cited_ts="20120701120000")
    citations: List[Dict[str, Any]] = [{
        "url": "<a page of the site that linked here>",
        "timestamp": "20120701120000",
        "anchor": "<the clickable text of the link>",
        "description": "<the summary of that citing page, from step 1>",
    }]
    parts.append(_section(
        "2. READING LINKED MATERIAL  (methodology step 4)",
        """Run for each page recovered from outside the site. It asks the same
questions as the pass above and one more: what the link was for. To answer that
the model is shown where the site linked from, the words it used for the link,
and the summary of the citing page -- so "relation" is judged from the citing
context and not from the linked page alone.""",
        links_svc.build_link_prompt(
            project=project, target=target, citations=citations,
            content=MARKER.format(n=8000), max_chars=10 ** 9)))

    # --- Step 5: the close reading ---------------------------------------------
    parts.append(_section(
        "3. CLOSE READING  (methodology step 5)",
        f"""Run once per article-shaped page. This is the pass that produces the
people and their roles, the places, the organizations, the events, the
assertions, the framings, the quoted speech, the genre, the register and the
two separate dates. Everything on reading.html and chronology.html comes from
it.

Decoding settings: temperature 0.2, top_p 0.9, num_predict
{reading_svc.READING_NUM_PREDICT}. The low temperature is deliberate -- this
step is extraction, not composition. Page text is truncated to
{reading_svc.READING_MAX_CHARS} characters, and the prompt caps the length of
every list it asks for, so a long interview cannot run the answer past the
token limit and truncate the JSON.""",
        reading_svc.build_reading_prompt(
            content=MARKER.format(n=reading_svc.READING_MAX_CHARS),
            url="<the page's original address>",
            timestamp="20120704120000",
            max_chars=10 ** 9)))

    # --- The closed vocabularies ------------------------------------------------
    parts.append(_section(
        "4. THE CLOSED VOCABULARIES",
        """Every categorical answer is forced into one of these lists, and an
answer outside a list is discarded rather than kept. The lists are English even
though the corpus is Spanish, so that filtering and counting stay stable across
a bilingual site; free text -- titles, summaries, framings, quotations -- is
kept in the language of the source.

The genre names are left in Spanish because they are terms of art in the press
this site belongs to, and translating "cronica" to "chronicle" would lose the
distinction it carries.""",
        "\n".join([
            _vocabulary("genre", reading_svc.GENRES),
            _vocabulary("intent", reading_svc.INTENTS),
            _vocabulary("stance", reading_svc.STANCES),
            _vocabulary("person role", reading_svc.PERSON_ROLES),
            _vocabulary("place kind", reading_svc.PLACE_KINDS),
            _vocabulary("organization kind", reading_svc.ORG_KINDS),
            _vocabulary("temporal mode", reading_svc.TEMPORAL_MODES),
            "",
            _vocabulary("link relation", links_svc.RELATIONS),
            _vocabulary("link content type", links_svc.LINK_CONTENT_TYPES),
        ])))

    return "\n".join(parts)
